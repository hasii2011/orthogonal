TRANSLATION_GRAPH_MEDIUM_PNG:  str = 'translationGraphMedium.png'


class TestGML(ProjectTestBase):

    @classmethod
    def setUpClass(cls):
        super().setUpClass()

    @classmethod
    def retrieveGoldenImagePath(cls, bareFileName: str) -> Path:
        fqFileName: str = ResourceManager.retrieveResourcePath(
            bareFileName=bareFileName,
            resourcePath=str(GOLDEN_IMAGES_PATH),
            packageName=GOLDEN_IMAGES_PACKAGE_NAME,
        )
        return Path(fqFileName)

    @classmethod
    def _showVisualDiffGui(cls, testName: str, goldenPath: Path, generatedPath: Path, diffPath: Path):
        """
        Display an interactive three-panel GUI comparison of golden, generated, and difference images.

        When running in a continuous integration environment (indicated by the presence of the 'CI'
        environment variable), this method exits early to ensure headless execution without attempting
        to attach to a display server.

        Args:
            testName: Identifier of the test case experiencing the image mismatch.
            goldenPath: Filesystem path to the golden benchmark image.
            generatedPath: Filesystem path to the newly generated test output image.
            diffPath: Filesystem path to the visual difference mask generated by compare_images.
        """
        if 'CI' in osEnviron:
            return

        fig: Any
        axes: Any
        fig, axes = plotSubplots(1, 3, figsize=(15, 5))
        if fig.canvas.manager is not None:
            fig.canvas.manager.set_window_title(f'Visual Diff: {testName}')

        axes[0].imshow(imageRead(str(goldenPath)))
        axes[0].set_title('Golden (Expected)')
        axes[1].imshow(imageRead(str(generatedPath)))
        axes[1].set_title('Generated (Actual)')
        axes[2].imshow(imageRead(str(diffPath)))
        axes[2].set_title('Difference')

        ax: Any
        for ax in axes:
            ax.axis('off')

        plotTightLayout()
        plotShow()

    def setUp(self):
        super().setUp()

