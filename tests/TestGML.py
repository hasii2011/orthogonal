OUTPUT_DIR: Path = Path('/tmp')

GOLDEN_IMAGES_PATH: Path        = Path('tests') / 'resources' / 'goldenimages'
GOLDEN_IMAGES_PACKAGE_NAME: str = 'tests.resources.goldenimages'

CASE1_PNG: str = 'case1.png'
CASE2_PNG: str = 'case2.png'
SIMPLE_PNG: str = 'simple.png'

CASE1_BICONNECTED_PNG: str = 'case1BiConnected.png'
